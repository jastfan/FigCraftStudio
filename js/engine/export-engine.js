/**
 * FigCraft Studio — Production Export Engine & Multi-Language Dev Mode Generator
 * Exports Hi-DPI PNG (1x, 2x, 3x), Clean SVG, CSS, React Tailwind, SwiftUI, and Tokens JSON.
 */

export class ExportEngine {
  static exportNodeToPNG(node, scale = 2) {
    const b = node.getBounds();
    const offscreen = document.createElement('canvas');
    offscreen.width = b.width * scale;
    offscreen.height = b.height * scale;
    const ctx = offscreen.getContext('2d');
    ctx.scale(scale, scale);

    this.renderNodeToCanvas(ctx, node, 0, 0);

    const link = document.createElement('a');
    link.download = `${(node.name || 'export').replace(/\s+/g, '_')}_${scale}x.png`;
    link.href = offscreen.toDataURL('image/png');
    link.click();
  }

  static renderNodeToCanvas(ctx, node, parentX, parentY) {
    if (!node.visible) return;
    const x = parentX + (parentX === 0 && parentY === 0 ? 0 : node.x);
    const y = parentY + (parentX === 0 && parentY === 0 ? 0 : node.y);

    ctx.save();
    ctx.globalAlpha = node.opacity;

    if (node.type === 'FRAME' || node.type === 'RECTANGLE' || node.type === 'COMPONENT') {
      ctx.fillStyle = node.fill || '#ffffff';
      if (node.cornerRadius > 0) {
        this.drawRoundedRect(ctx, x, y, node.width, node.height, node.cornerRadius);
        ctx.fill();
      } else {
        ctx.fillRect(x, y, node.width, node.height);
      }
    } else if (node.type === 'ELLIPSE') {
      ctx.fillStyle = node.fill || '#a855f7';
      ctx.beginPath();
      ctx.ellipse(x + node.width / 2, y + node.height / 2, node.width / 2, node.height / 2, 0, 0, Math.PI * 2);
      ctx.fill();
    } else if (node.type === 'TEXT') {
      ctx.fillStyle = node.fill || '#18181b';
      ctx.font = `${node.fontWeight || '400'} ${node.fontSize || 16}px ${node.fontFamily || 'sans-serif'}`;
      ctx.textBaseline = 'top';
      ctx.fillText(node.text || '', x, y);
    } else if (node.type === 'VECTOR' && node.vertices && node.vertices.length > 1) {
      ctx.beginPath();
      ctx.moveTo(x + (node.vertices[0].x - node.x), y + (node.vertices[0].y - node.y));
      for (let i = 1; i < node.vertices.length; i++) {
        ctx.lineTo(x + (node.vertices[i].x - node.x), y + (node.vertices[i].y - node.y));
      }
      if (node.closed) {
        ctx.closePath();
        if (node.fill && node.fill !== 'transparent') {
          ctx.fillStyle = node.fill;
          ctx.fill();
        }
      }
    }

    if (node.stroke) {
      ctx.strokeStyle = node.stroke;
      ctx.lineWidth = node.strokeWidth || 1;
      ctx.stroke();
    }

    // Children
    for (const child of node.children) {
      this.renderChildRecursive(ctx, child, x, y);
    }

    ctx.restore();
  }

  static renderChildRecursive(ctx, child, parentX, parentY) {
    if (!child.visible) return;
    const x = parentX + child.x;
    const y = parentY + child.y;

    ctx.save();
    ctx.globalAlpha = child.opacity;

    if (child.type === 'RECTANGLE' || child.type === 'FRAME' || child.type === 'COMPONENT') {
      ctx.fillStyle = child.fill || '#ffffff';
      if (child.cornerRadius > 0) {
        this.drawRoundedRect(ctx, x, y, child.width, child.height, child.cornerRadius);
        ctx.fill();
      } else {
        ctx.fillRect(x, y, child.width, child.height);
      }
    } else if (child.type === 'ELLIPSE') {
      ctx.fillStyle = child.fill || '#a855f7';
      ctx.beginPath();
      ctx.ellipse(x + child.width / 2, y + child.height / 2, child.width / 2, child.height / 2, 0, 0, Math.PI * 2);
      ctx.fill();
    } else if (child.type === 'TEXT') {
      ctx.fillStyle = child.fill || '#18181b';
      ctx.font = `${child.fontWeight || '400'} ${child.fontSize || 16}px ${child.fontFamily || 'sans-serif'}`;
      ctx.textBaseline = 'top';
      ctx.fillText(child.text || '', x, y);
    }

    if (child.stroke) {
      ctx.strokeStyle = child.stroke;
      ctx.lineWidth = child.strokeWidth || 1;
      ctx.stroke();
    }

    for (const sub of child.children) {
      this.renderChildRecursive(ctx, sub, x, y);
    }
    ctx.restore();
  }

  // --- Clean Standalone SVG Export ---
  static exportNodeToSVG(node) {
    const b = node.getBounds();
    let body = this.nodeToSVGElement(node, 0, 0);

    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg width="${Math.round(b.width)}" height="${Math.round(b.height)}" viewBox="0 0 ${Math.round(b.width)} ${Math.round(b.height)}" fill="none" xmlns="http://www.w3.org/2000/svg">
  <!-- Generated by FigCraft Studio (Clean-Room Engine) -->
  ${body}
</svg>`;

    const blob = new Blob([svg], { type: 'image/svg+xml' });
    const link = document.createElement('a');
    link.download = `${(node.name || 'vector_art').replace(/\s+/g, '_')}.svg`;
    link.href = URL.createObjectURL(blob);
    link.click();
    return svg;
  }

  static nodeToSVGElement(node, parentX, parentY) {
    const x = parentX + node.x;
    const y = parentY + node.y;
    let out = '';

    const fillAttr = node.fill ? `fill="${node.fill}"` : 'fill="none"';
    const strokeAttr = node.stroke ? `stroke="${node.stroke}" stroke-width="${node.strokeWidth || 1}"` : '';

    if (node.type === 'FRAME' || node.type === 'RECTANGLE' || node.type === 'COMPONENT') {
      out += `<rect x="${x}" y="${y}" width="${node.width}" height="${node.height}" rx="${node.cornerRadius || 0}" ${fillAttr} ${strokeAttr} />\n`;
    } else if (node.type === 'ELLIPSE') {
      const cx = x + node.width / 2;
      const cy = y + node.height / 2;
      out += `<ellipse cx="${cx}" cy="${cy}" rx="${node.width / 2}" ry="${node.height / 2}" ${fillAttr} ${strokeAttr} />\n`;
    } else if (node.type === 'TEXT') {
      out += `<text x="${x}" y="${y + (node.fontSize || 16)}" font-family="${node.fontFamily || 'Inter'}" font-size="${node.fontSize || 16}" font-weight="${node.fontWeight || '400'}" fill="${node.fill || '#000'}">${escapeXml(node.text || '')}</text>\n`;
    } else if (node.type === 'VECTOR' && node.vertices && node.vertices.length > 1) {
      let d = `M ${x + (node.vertices[0].x - node.x)} ${y + (node.vertices[0].y - node.y)}`;
      for (let i = 1; i < node.vertices.length; i++) {
        d += ` L ${x + (node.vertices[i].x - node.x)} ${y + (node.vertices[i].y - node.y)}`;
      }
      if (node.closed) d += ' Z';
      out += `<path d="${d}" ${fillAttr} ${strokeAttr} />\n`;
    }

    for (const child of node.children) {
      out += this.nodeToSVGElement(child, x, y);
    }
    return out;
  }

  // --- Dev Mode: CSS Generator ---
  static generateCSS(node) {
    if (!node) return '/* Select a layer to inspect CSS */';
    const lines = [];
    lines.push(`/* Layer: ${node.name} (${node.type}) */`);
    lines.push(`position: absolute;`);
    lines.push(`width: ${Math.round(node.width)}px;`);
    lines.push(`height: ${Math.round(node.height)}px;`);
    lines.push(`left: ${Math.round(node.x)}px;`);
    lines.push(`top: ${Math.round(node.y)}px;`);

    if (node.fill && node.fill !== 'transparent') {
      lines.push(`background: ${node.fill};`);
    }
    if (node.cornerRadius > 0) {
      lines.push(`border-radius: ${node.cornerRadius}px;`);
    }
    if (node.stroke) {
      lines.push(`border: ${node.strokeWidth || 1}px ${node.strokeStyle || 'solid'} ${node.stroke};`);
    }
    if (node.opacity < 1.0) {
      lines.push(`opacity: ${node.opacity};`);
    }

    if ((node.type === 'FRAME' || node.type === 'COMPONENT') && node.autoLayout && node.autoLayout.enabled) {
      const cfg = node.autoLayout;
      lines.push(`display: flex;`);
      lines.push(`flex-direction: ${cfg.direction === 'HORIZONTAL' ? 'row' : 'column'};`);
      lines.push(`gap: ${cfg.gap || 0}px;`);
      lines.push(`padding: ${cfg.paddingTop}px ${cfg.paddingRight}px ${cfg.paddingBottom}px ${cfg.paddingLeft}px;`);
      lines.push(`align-items: ${cfg.alignItems.toLowerCase()};`);
      lines.push(`justify-content: ${cfg.justifyContent === 'SPACE_BETWEEN' ? 'space-between' : cfg.justifyContent.toLowerCase()};`);
    }

    if (node.type === 'TEXT') {
      lines.push(`font-family: ${node.fontFamily};`);
      lines.push(`font-size: ${node.fontSize}px;`);
      lines.push(`font-weight: ${node.fontWeight};`);
      lines.push(`color: ${node.fill};`);
      lines.push(`text-align: ${node.textAlign};`);
      lines.push(`line-height: ${node.lineHeight};`);
    }

    return lines.join('\n');
  }

  // --- Dev Mode: React Tailwind Generator ---
  static generateReactTailwind(node) {
    if (!node) return '// Select a layer to inspect React + Tailwind';
    const classes = [];
    classes.push(`w-[${Math.round(node.width)}px]`);
    classes.push(`h-[${Math.round(node.height)}px]`);

    if (node.cornerRadius > 0) {
      classes.push(`rounded-[${node.cornerRadius}px]`);
    }

    if ((node.type === 'FRAME' || node.type === 'COMPONENT') && node.autoLayout && node.autoLayout.enabled) {
      classes.push('flex');
      classes.push(node.autoLayout.direction === 'HORIZONTAL' ? 'flex-row' : 'flex-col');
      classes.push(`gap-[${node.autoLayout.gap || 12}px]`);
      classes.push(`p-[${node.autoLayout.paddingTop || 16}px]`);
    }

    if (node.type === 'TEXT') {
      classes.push(`text-[${node.fontSize}px]`);
      classes.push(`font-[${node.fontWeight}]`);
      return `export function ${sanitizeIdentifier(node.name)}() {\n  return (\n    <p className="${classes.join(' ')}" style={{ color: '${node.fill}' }}>\n      ${node.text}\n    </p>\n  );\n}`;
    }

    return `export function ${sanitizeIdentifier(node.name)}() {\n  return (\n    <div className="${classes.join(' ')}" style={{ backgroundColor: '${node.fill}' }}>\n      {/* Child layers */}\n    </div>\n  );\n}`;
  }

  // --- Dev Mode: SwiftUI Generator ---
  static generateSwiftUI(node) {
    if (!node) return '// Select a layer to inspect SwiftUI';
    if (node.type === 'TEXT') {
      return `Text("${node.text}")\n  .font(.system(size: ${node.fontSize}, weight: .semibold))\n  .foregroundColor(Color(hex: "${node.fill}"))\n  .frame(width: ${node.width}, height: ${node.height}, alignment: .leading)`;
    }

    const isHStack = (node.type === 'FRAME' || node.type === 'COMPONENT') && node.autoLayout && node.autoLayout.direction === 'HORIZONTAL';
    const container = isHStack ? 'HStack' : 'VStack';

    return `${container}(spacing: ${(node.autoLayout && node.autoLayout.gap) || 12}) {\n    // Inner child views\n}\n.frame(width: ${node.width}, height: ${node.height})\n.background(Color(hex: "${node.fill}"))\n.cornerRadius(${node.cornerRadius || 0})`;
  }

  static drawRoundedRect(ctx, x, y, width, height, radius) {
    ctx.beginPath();
    ctx.moveTo(x + radius, y);
    ctx.lineTo(x + width - radius, y);
    ctx.quadraticCurveTo(x + width, y, x + width, y + radius);
    ctx.lineTo(x + width, y + height - radius);
    ctx.quadraticCurveTo(x + width, y + height, x + width - radius, y + height);
    ctx.lineTo(x + radius, y + height);
    ctx.quadraticCurveTo(x, y + height, x, y + height - radius);
    ctx.lineTo(x, y + radius);
    ctx.quadraticCurveTo(x, y, x + radius, y);
    ctx.closePath();
  }
}

function escapeXml(unsafe) {
  return unsafe.replace(/[<>&'"]/g, (c) => {
    switch (c) {
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '&': return '&amp;';
      case '\'': return '&apos;';
      case '"': return '&quot;';
    }
  });
}

function sanitizeIdentifier(name) {
  return (name || 'Component').replace(/[^a-zA-Z0-9]/g, '');
}
